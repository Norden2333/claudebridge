import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
const run=promisify(execFile);
test('source checker rejects stale generated tools and credential-bearing offline subprocesses',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'cfb-source-policy-'));
 t.after(()=>fs.rm(root,{recursive:true,force:true}));
 for(const dir of ['tools','extension','companion','vendor/remote-device','tests'])await fs.mkdir(path.join(root,dir),{recursive:true});
 const write=(name,value)=>fs.writeFile(path.join(root,name),value);
 await fs.copyFile(new URL('../tools/check-source.mjs',import.meta.url),path.join(root,'tools/check-source.mjs'));
 await write('companion/files.mjs','export const definitions=[];');
 await write('package.json',JSON.stringify({type:'module',version:'0.5.5'}));
 await write('extension/manifest.json',JSON.stringify({version:'0.5.5'}));
 await write('extension/protocol.js',"const SERVER_VERSION = '0.5.5';");
 await write('tools/windows-launcher.cs','AssemblyVersion("0.5.5.0")');
 for(const name of ['options','popup','workspace'])await write('extension/'+name+'.html','Claude 文件连接 · 0.5.5');
 for(const name of ['安装-Windows.ps1','卸载-Windows.ps1','更新与切回-Windows.ps1','Windows安装向导.ps1'])await write(name,'param()');
 await write('vendor/remote-device/remote-channel.js','export const safe=true;');
 await write('extension/tools.js','self.CFB_TOOL_DEFINITIONS = [];\n');
 const check=()=>run(process.execPath,[path.join(root,'tools/check-source.mjs')],{timeout:15000});
 await check();
 await write('extension/tools.js','self.CFB_TOOL_DEFINITIONS = [{name:"stale"}];\n');
 await assert.rejects(check(),e=>e.code!==0&&e.stderr.includes('tools.js'));
 await write('extension/tools.js','self.CFB_TOOL_DEFINITIONS = [];\n');
 await write('vendor/remote-device/remote-channel.js',"const spawnSync=()=>{};spawnSync('node',['obsolete',session.access_token]);");
 await assert.rejects(check(),e=>e.code!==0&&e.stderr.includes('登录令牌'));
});
